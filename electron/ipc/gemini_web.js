async function resolvePartitionForTarget(emailOrProfileId) {
  try {
    const config = await loadProfiles()
    if (config && config.profiles) {
      // 1. Exact match by Flow profile ID or Email (Unifying Google Flow and Gemini AI accounts!)
      let matched = config.profiles.find(
        (p) =>
          p.id === emailOrProfileId ||
          (p.email &&
            emailOrProfileId &&
            p.email.toLowerCase().trim() === emailOrProfileId.toLowerCase().trim())
      )
      if (matched) {
        return {
          partition:
            matched.id === 'default'
              ? 'persist:flow_profile_default'
              : `persist:flow_profile_${matched.id}`,
          profile: matched,
          isFlowProfile: true
        }
      }
    }
  } catch (err) {
    console.warn('[Gemini Web IPC] resolvePartitionForTarget error:', err)
  }

  // 2. If it's a new email not yet in Flow profiles, auto-register as a new Flow profile for unified management!
  if (emailOrProfileId && emailOrProfileId.includes('@')) {
    try {
      const created = await createProfile(emailOrProfileId.split('@')[0], emailOrProfileId.trim())
      if (created && created.success && created.profile) {
        return {
          partition:
            created.profile.id === 'default'
              ? 'persist:flow_profile_default'
              : `persist:flow_profile_${created.profile.id}`,
          profile: created.profile,
          isFlowProfile: true
        }
      }
    } catch (e) {
      console.warn('[Gemini Web IPC] Auto-create flow profile failed:', e)
    }

    const cleanKey = emailOrProfileId.trim().toLowerCase().replace(/[^a-z0-9]/g, '_')
    return {
      partition: `persist:flow_profile_${cleanKey}`,
      profile: { id: cleanKey, name: emailOrProfileId, email: emailOrProfileId },
      isFlowProfile: true
    }
  }

  // 3. Fallback: only when no email and no profile ID was given (default flow profile)
  return { partition: 'persist:flow_profile_default', profile: null, isFlowProfile: true }
}

