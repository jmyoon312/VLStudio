function cookiesToNetscape(cookies) {
  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by ViraLoop Studio for Google Gemini Web',
    '# Created at ' + new Date().toISOString(),
    ''
  ]

  for (const c of cookies) {
    const domain = c.domain || ''
    const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE'
    const pathVal = c.path || '/'
    const secure = c.secure ? 'TRUE' : 'FALSE'
    let expiration = Math.floor(c.expirationDate || 0)
    if (expiration <= 0) {
      expiration = Math.floor(Date.now() / 1000) + 86400 * 365
    }
    lines.push([domain, includeSubdomains, pathVal, secure, expiration, c.name, c.value].join('\t'))
  }
  return lines.join('\n') + '\n'
}

async function notifyBackendSession(sessionData) {
  return new Promise((resolve) => {
    try {
      const payload = JSON.stringify(sessionData)
      const req = http.request(
        {
          hostname: '127.0.0.1',
          port: 8000,
          path: '/api/ai-accounts/gemini/web-session',
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'Content-Length': Buffer.byteLength(payload)
          }
        },
        (res) => {
          resolve(res.statusCode === 200)
        }
      )
      req.on('error', () => resolve(false))
      req.write(payload)
      req.end()
    } catch {
      resolve(false)
    }
  })
}

